const assert = require('node:assert/strict');
const {chromium} = require('playwright');

(async () => {
  const browser = await chromium.launch({headless: true});
  try {
    const page = await browser.newPage();
    page.setDefaultTimeout(10000);
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    const read = () => page.evaluate(async () => (await fetch('/api/state')).json());
    const saved = () => page.waitForFunction(() => document.querySelector('#save-status').textContent === 'All changes saved ✓');
    await page.goto(process.argv[2]);
    await page.waitForFunction(() => document.querySelector('#render-status').textContent === 'Preview up to date ✓');
    const original = await read();
    const originalBullets = original.catalog.projects[0].role.bullets;
    await page.locator('[data-section="projects"]').click();
    assert.equal(await page.locator('#employer-picker option').count(), 2);
    assert.equal((await read()).revision, original.revision);
    await page.getByRole('textbox', {name: 'Technology keywords', exact: true}).fill('Java, PostgreSQL');
    await saved();
    await page.locator('#split-project').click();
    await page.locator('#create-name').fill('Service platform');
    await page.locator('#create-form').getByRole('button', {name: 'Create draft', exact: true}).click();
    await page.getByRole('textbox', {name: 'Project name', exact: true}).waitFor();
    assert.equal(await page.getByRole('textbox', {name: 'Technology keywords', exact: true}).inputValue(), 'Java, PostgreSQL');
    const grouped = await read();
    assert.deepEqual(grouped.catalog.variants[0].project_overrides.services.entry.bullets, originalBullets);
    await page.locator('#add-employer-project').click();
    await page.locator('#create-name').fill('Notifications');
    await page.locator('#create-first-bullet').fill('Implemented notification delivery tests.');
    await page.locator('#create-project-tech').fill('Python, HTTP');
    await page.locator('#create-form').getByRole('button', {name: 'Create draft', exact: true}).click();
    await page.waitForFunction(() => document.querySelector('#project-picker').selectedOptions[0].textContent === 'Notifications');
    const added = await read();
    const addedId = added.selection.project_ids.find(id => !grouped.selection.project_ids.includes(id));
    assert.ok(addedId);
    assert.equal(await page.getByRole('textbox', {name: 'Bullet 1', exact: true}).inputValue(), 'Implemented notification delivery tests.');
    await page.getByRole('textbox', {name: 'Bullet 1', exact: true}).fill('Candidate revised the notification delivery bullet.');
    await saved();
    await page.locator('details[data-details-key="employer-details"] > summary').click();
    await page.getByRole('textbox', {name: 'Dates', exact: true}).fill('2020 - 2025');
    await saved();
    const renamed = await read();
    assert.equal(renamed.catalog.variants[0].project_overrides.services.role.dates, '2020 - 2025');
    assert.equal(renamed.catalog.variants[0].project_overrides[addedId].role.dates, '2020 - 2025');
    assert.equal(renamed.catalog.projects[1].role.dates, '2020 - Present');
    await page.locator('#project-picker').selectOption('services');
    assert.equal(await page.getByRole('textbox', {name: 'Technology keywords', exact: true}).inputValue(), 'Java, PostgreSQL');
    assert.equal(await page.getByRole('textbox', {name: 'Bullet 1', exact: true}).inputValue(), originalBullets[0]);
    await page.reload();
    await page.locator('[data-section="projects"]').click();
    assert.equal(await page.locator('#project-picker option').count(), 2);
    await page.locator('#project-picker').selectOption(addedId);
    assert.equal(await page.getByRole('textbox', {name: 'Bullet 1', exact: true}).inputValue(), 'Candidate revised the notification delivery bullet.');
    const preview = await page.evaluate(async () => (await fetch('/api/preview')).json());
    assert.equal(preview.audit_ok, true);
    for (const text of ['Service platform', 'Notifications', 'Python, HTTP', 'Candidate revised the notification delivery bullet.']) assert.ok(preview.text.includes(text), text);
    await page.locator('#remove-employer-project').click();
    await page.waitForFunction(() => document.querySelector('#project-picker').options.length === 1);
    assert.deepEqual((await read()).catalog.variants[0].project_overrides.services.entry.bullets, originalBullets);
    await page.locator('#undo').click();
    await page.waitForFunction(() => document.querySelector('#project-picker').options.length === 2);
    const final = await read();
    assert.equal(final.catalog.variants[0].project_overrides[addedId].entry.bullets[0], 'Candidate revised the notification delivery bullet.');
    assert.deepEqual(errors, []);
    console.log('Employer grouping, split preservation, project keywords, independent bullets, shared headers, reload, PDF and undo passed');
  } finally {
    await browser.close();
  }
})().catch(error => { console.error(error.stack); process.exit(1); });
